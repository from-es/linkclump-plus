/**
 * Valid mouse button codes matching DOM MouseEvent.button specification.
 * -1: No button pressed (initial/reset state)
 *  0: Main button pressed, usually the left button
 *  1: Auxiliary button pressed, usually the wheel button or the middle button
 *  2: Secondary button pressed, usually the right button
 */
export type MouseButtonType = -1 | 0 | 1 | 2;
